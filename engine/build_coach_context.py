"""
Builds data/coach_context.json -- the briefing the AI Coach (/coach/) reads.
One compact plain-text briefing per team (record, results, gate, cash,
roster, injuries, next opponent) plus the league table and the rulebook
text. backend.gs (type "coach_chat") fetches this file from GitHub Pages
server-side and hands ONLY the asking team's briefing + the rulebook to
Gemini, so a student can't swap in another team's context.

Deliberately left out: PINs, rationale_scores.csv / scorecard grades,
forfeit flags and reasons (instructor-only, see push_forfeit_tab.py), and
sponsor base_revenue (never public, see backend.gs catalog handler).
Regenerated by auto_resolve.regenerate_all_pages() every cycle.
"""
import html
import json
import os
import re
import sys
from datetime import datetime, timezone

sys.path.insert(0, os.path.dirname(__file__))
import render_dashboard
import resolve_trade
from player_condition import conditions_for_round

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
POS_ORDER = {"GK": 0, "DF": 1, "MF": 2, "FW": 3}


def load_json(name, default=None):
    path = os.path.join(BASE, "data", name)
    if not os.path.exists(path):
        return default
    with open(path) as f:
        return json.load(f)


def money(n):
    return f"${int(n):,}"


def rulebook_text():
    path = os.path.join(BASE, "rulebook", "index.html")
    if not os.path.exists(path):
        return ""
    t = open(path).read()
    t = re.sub(r"<nav[\s\S]*?</nav>", " ", t)
    t = re.sub(r"<(script|style)[\s\S]*?</\1>", " ", t)
    t = re.sub(r"</(p|li|tr|h[1-6]|div|section)>", "\n", t)
    t = re.sub(r"<[^>]+>", " ", t)
    t = html.unescape(t)
    t = re.sub(r"[ \t]+", " ", t)
    return re.sub(r"\n\s*\n+", "\n", t).strip()


def team_results(tid, matches, names):
    lines = []
    for m in matches:
        if tid not in (m["home_id"], m["away_id"]):
            continue
        home = m["home_id"] == tid
        gf, ga = (m["home_goals"], m["away_goals"]) if home else (m["away_goals"], m["home_goals"])
        res = "W" if gf > ga else ("L" if gf < ga else "D")
        if m.get("forfeit") == "both":
            res = "L"
        opp = names[m["away_id"] if home else m["home_id"]]
        side = "home" if home else "away"
        formation = m.get(f"{side}_formation", "?")
        strategy = m.get(f"{side}_strategy", "?")
        gate = m.get("gate") or {}
        if home:
            gate_txt = (f"ticket ${gate.get('price', 0)} ({gate.get('price_tier') or 'n/a'} tier), "
                        f"attendance {gate.get('attendance', 0):,} ({round(100 * (gate.get('attendance_rate') or 0))}% full), "
                        f"your gate revenue {money(gate.get('home_revenue', 0))}")
        else:
            gate_txt = f"away gate share {money(gate.get('away_revenue', 0))}"
        lines.append(f"R{m['round']} {side} vs {opp}: {res} {gf}-{ga} | {formation} {strategy} | {gate_txt}")
    return lines


def main():
    config = load_json("league_config.json")
    matches = load_json("matches.json", [])
    schedule = load_json("schedule.json", [])
    finances = load_json("team_finances.json", {"teams": {}})
    injuries = load_json("player_injuries.json", {})
    trades_state = resolve_trade.load_trades_state()
    players = render_dashboard.load_players()

    names = {t["team_id"]: t["name"] for t in config["teams"]}
    team_ids = list(names.keys())
    ranked = render_dashboard.build_standings(matches, team_ids)
    position = {tid: i + 1 for i, (tid, _row) in enumerate(ranked)}
    table_lines = [
        f"{i + 1}. {names[tid]} -- P{r['P']} W{r['W']} D{r['D']} L{r['L']} GF{r['GF']} GA{r['GA']} Pts{r['PTS']}"
        for i, (tid, r) in enumerate(ranked)
    ]

    next_round = config.get("current_round", 0) + 1
    _m, cond = conditions_for_round(config.get("season_seed", 2026), next_round, players, injuries)
    next_fixture = {}
    for rnd in schedule:
        if rnd["round"] == next_round:
            for f in rnd["fixtures"]:
                next_fixture[f["home_id"]] = (f["away_id"], "home")
                next_fixture[f["away_id"]] = (f["home_id"], "away")

    rosters = {tid: [] for tid in team_ids}
    for p in players:
        if p["team_id"] not in ("", None):
            rosters[int(p["team_id"])].append(p)

    def squad_summary(tid):
        squad = rosters[tid]
        if not squad:
            return "no roster yet", 0
        avg = round(sum(p["ovr"] for p in squad) / len(squad), 1)
        return f"{len(squad)} players, average OVR {avg}", avg

    teams_out = {}
    for tid in team_ids:
        rec = dict(ranked)[tid]
        squad = sorted(rosters[tid], key=lambda p: (POS_ORDER.get(p["position"], 4), -p["ovr"]))
        payroll = sum(p["salary"] for p in squad)
        fin = finances["teams"].get(str(tid), {})
        cash = resolve_trade.team_available_cash(finances, config, trades_state, tid)
        roster_lines = []
        for p in squad:
            tier, _mult, inj_until = cond.get(p["player_id"], ("Average", 1.0, None))
            status = f"INJURED through R{inj_until}" if inj_until else f"condition {tier}"
            roster_lines.append(f"{p['position']} {p['name']} OVR{p['ovr']} (ATT{p['att']} DEF{p['def']} "
                                f"PACE{p['pace']} PHY{p['phy']}, star {p['star_power']}, age {p['age']}, "
                                f"salary {money(p['salary'])}) {status}")
        summary, _avg = squad_summary(tid)
        if tid in next_fixture:
            opp, side = next_fixture[tid]
            orec = dict(ranked)[opp]
            osum, _ = squad_summary(opp)
            next_txt = (f"Round {next_round}: {side} vs {names[opp]} (position {position[opp]}, "
                        f"W{orec['W']} D{orec['D']} L{orec['L']}, {osum})")
        else:
            next_txt = "no fixture scheduled"
        sponsors = fin.get("sponsors_owned") or []
        sponsor_txt = ", ".join(s if isinstance(s, str) else s.get("brand", str(s)) for s in sponsors) or "none signed yet"
        briefing = "\n".join([
            f"TEAM: {names[tid]} (league position {position[tid]} of {len(team_ids)})",
            f"RECORD: P{rec['P']} W{rec['W']} D{rec['D']} L{rec['L']}, GF{rec['GF']} GA{rec['GA']}, {rec['PTS']} pts",
            f"NEXT MATCH: {next_txt}",
            "RESULTS SO FAR:",
            *(["  " + l for l in team_results(tid, matches, names)] or ["  none played yet"]),
            f"FINANCES: cash available {money(cash)} (starting budget {money(config.get('starting_budget', 0))}); "
            f"ticket revenue {money(fin.get('ticket_revenue', 0))}, sponsorship {money(fin.get('sponsorship_revenue', 0))}, "
            f"national TV {money(fin.get('tv_revenue', 0))}, local TV {money(fin.get('local_tv_revenue', 0))}",
            f"PAYROLL: {money(payroll)} of the {money(config.get('salary_cap', 0))} salary cap",
            f"SPONSORS: {sponsor_txt} ({config.get('sponsorship_categories_required', 6)} categories required)",
            f"SQUAD: {summary}",
            *("  " + l for l in roster_lines),
        ])
        teams_out[str(tid)] = {"name": names[tid], "position": position[tid],
                               "record": f"{rec['W']}W-{rec['D']}D-{rec['L']}L", "points": rec["PTS"],
                               "cash": cash, "next": next_txt, "briefing": briefing}

    out = {
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "league_name": config["league_name"],
        "current_round": config.get("current_round", 0),
        "league_table": "\n".join(table_lines),
        "teams": teams_out,
        "rulebook": rulebook_text(),
    }
    with open(os.path.join(BASE, "data", "coach_context.json"), "w") as f:
        json.dump(out, f, indent=1)
    print(f"coach_context.json OK ({len(teams_out)} teams, rulebook {len(out['rulebook'])} chars)")


if __name__ == "__main__":
    main()
